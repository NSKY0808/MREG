"""Export public JSON Schemas and reason-code documentation from source contracts."""

from pathlib import Path

from mreg.gate.reason_codes import REASONS
from mreg.models.evidence import Evidence
from mreg.models.policy import Policy
from mreg.models.result import Result
from mreg.reporting.json_report import write_json

ROOT = Path(__file__).resolve().parents[1]


def export() -> None:
    (ROOT / "schemas").mkdir(exist_ok=True)
    for name, model in [("evidence", Evidence), ("policy", Policy), ("result", Result)]:
        schema = model.model_json_schema()
        schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
        write_json(ROOT / "schemas" / f"{name}.schema.json", schema)
    lines = [
        "# Public reason-code registry",
        "",
        "Generated by scripts/export_schemas.py. Existing codes are stable within schema 1.x.",
        "",
        "| Code | Meaning |",
        "|---|---|",
    ]
    lines.extend(f"| `{code}` | {meaning} |" for code, meaning in REASONS.items())
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs/REASON_CODES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    export()
